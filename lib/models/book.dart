enum BookAccess { free, purchase, rental }

class Book {
  const Book({
    required this.id,
    required this.title,
    required this.author,
    required this.category,
    required this.price,
    required this.pages,
    required this.rating,
    required this.coverStart,
    required this.coverEnd,
    required this.coverMark,
    this.isAdult = false,
    this.isNew = false,
    this.access = BookAccess.purchase,
    this.description =
        'Бул чыгарма окурманды өзгөчө дүйнөгө жетелеп, адамдык тандоо, сүйүү жана үмүт жөнүндө баяндайт.',
  });

  final String id;
  final String title;
  final String author;
  final String category;
  final int price;
  final int pages;
  final double rating;
  final int coverStart;
  final int coverEnd;
  final String coverMark;
  final bool isAdult;
  final bool isNew;
  final BookAccess access;
  final String description;

  bool get isFree => access == BookAccess.free || price == 0;
}

